/*
# Create app tables: profiles, oil_logs, daily_summaries, alerts

1. New Tables
  - `profiles`: one row per user, stores onboarding data (name, age, BMI, activity level,
    pre-existing conditions, household size, state, zone). user_id maps to auth.users.
  - `oil_logs`: per-meal oil intake entries (breakfast/lunch/dinner) with oil type,
    quantity in grams, cooking method, and date. Owned by the authenticated user.
  - `daily_summaries`: one row per user per day with total grams consumed, oil quality
    class, and risk level. Upserted after each log. Composite PK on (user_id, log_date).
  - `alerts`: in-app notifications (info/warning/critical) generated by the AI pipeline.
    Owned by the authenticated user.

2. Security
  - RLS enabled on all four tables.
  - All tables are owner-scoped: each authenticated user can only SELECT/INSERT/UPDATE/DELETE
    their own rows (auth.uid() = user_id). The user_id column defaults to auth.uid() so
    inserts that omit user_id still satisfy the WITH CHECK policy.
  - survey_benchmarks remains public-read (already handled in prior migration).

3. Notes
  - Indexes added on oil_logs(user_id, log_date) and daily_summaries(user_id, log_date)
    for fast dashboard queries.
  - alerts includes a `read` boolean defaulting to false for unread tracking.
*/

CREATE TABLE IF NOT EXISTS profiles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL,
  age int NOT NULL,
  bmi numeric NOT NULL,
  activity_level text NOT NULL,
  pre_existing_conditions text[] DEFAULT '{}',
  household_size int NOT NULL,
  state text NOT NULL,
  zone text NOT NULL,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "select_own_profiles" ON profiles;
CREATE POLICY "select_own_profiles" ON profiles FOR SELECT
  TO authenticated USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "insert_own_profiles" ON profiles;
CREATE POLICY "insert_own_profiles" ON profiles FOR INSERT
  TO authenticated WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "update_own_profiles" ON profiles;
CREATE POLICY "update_own_profiles" ON profiles FOR UPDATE
  TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "delete_own_profiles" ON profiles;
CREATE POLICY "delete_own_profiles" ON profiles FOR DELETE
  TO authenticated USING (auth.uid() = user_id);

CREATE TABLE IF NOT EXISTS oil_logs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
